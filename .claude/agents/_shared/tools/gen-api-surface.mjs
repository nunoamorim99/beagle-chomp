#!/usr/bin/env node
/**
 * Regenerates .claude/agents/_shared/api-surface/* from the three.js version
 * installed in this project. Run it after every three.js upgrade:
 *
 *   node .claude/agents/_shared/tools/gen-api-surface.mjs
 *
 * The output is a plain-text, greppable list of every symbol that actually
 * exists in the installed build. It is the fastest way to answer
 * "is this a real API name in this revision?" without guessing.
 */
import { readdirSync, statSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname, relative } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createRequire } from 'node:module';

const here = dirname(fileURLToPath(import.meta.url));
const outDir = join(here, '..', 'api-surface');
mkdirSync(outDir, { recursive: true });
// Resolve three from the CURRENT WORKING DIRECTORY, so this works wherever the
// script file happens to live. Run it from the project root.
const require = createRequire(join(process.cwd(), 'package.json'));

let version = 'unknown', threeRoot = null;
try {
  // Some packages block deep access to package.json via "exports", so derive the
  // package root from the resolved main entry instead of resolving package.json.
  const main = require.resolve('three');
  const marker = join('node_modules', 'three');
  const i = main.lastIndexOf(marker);
  threeRoot = i >= 0 ? main.slice(0, i + marker.length) : dirname(dirname(main));
  version = JSON.parse(readFileSync(join(threeRoot, 'package.json'), 'utf8')).version;
} catch (e) {
  console.error('Cannot resolve "three" from ' + process.cwd() + ' — run this from your project root.');
  process.exit(1);
}

const kindOf = (v, name) => {
  if (typeof v === 'function') return /^[A-Z]/.test(name) ? 'class' : 'function';
  if (typeof v === 'object' && v !== null) return 'object';
  return 'const';
};

// Static fallback: some builds (three/webgpu before ~r171) touch browser globals
// at module scope and cannot be imported in Node. Their export names are still
// readable from the bundle's trailing `export { ... }` statements. Kinds are
// unknowable on that path, so every row is written as `symbol`.
function staticExports(file) {
  const src = readFileSync(file, 'utf8');
  const names = new Set();
  for (const m of src.matchAll(/^export\s*\{([^}]*)\}/gm))
    for (const part of m[1].split(','))
      { const t = part.trim().split(/\s+as\s+/).pop().trim(); if (t && t !== 'default') names.add(t); }
  for (const m of src.matchAll(/^export\s+(?:async\s+)?(?:class|function|const|let|var)\s+([A-Za-z_$][\w$]*)/gm)) names.add(m[1]);
  return names;
}

async function dumpEntry(specifier, file) {
  let resolved;
  try { resolved = require.resolve(specifier); }
  catch (e) { console.error(`skip ${specifier}: ${e.message}`); return 0; }
  let rows, how = 'imported';
  try {
    const ns = await import(pathToFileURL(resolved).href);
    rows = Object.keys(ns).sort().map(n => `${kindOf(ns[n], n)}\t${n}`);
  } catch (e) {
    const names = staticExports(resolved);
    if (!names.size) { console.error(`skip ${specifier}: ${e.message}`); return 0; }
    how = `parsed statically — not importable in Node (${e.message})`;
    rows = [...names].sort().map(n => `symbol\t${n}`);
  }
  writeFileSync(join(outDir, file),
    `# exports of "${specifier}" — three@${version}\n` +
    `# resolved to ${relative(threeRoot, resolved).split(/[\\/]/).join('/')} in three, ${how}.\n` +
    `# ${rows.length} symbols. Generated by gen-api-surface.mjs; do not edit.\n` +
    `# kind<TAB>name\n` + rows.join('\n') + '\n');
  return rows.length;
}

// --- addon modules: walk examples/jsm and read export statements -------------
function walk(dir, acc = []) {
  for (const e of readdirSync(dir)) {
    const p = join(dir, e);
    if (statSync(p).isDirectory()) walk(p, acc);
    else if (e.endsWith('.js')) acc.push(p);
  }
  return acc;
}
function addonExports(root) {
  const jsm = join(root, 'examples', 'jsm');
  let files = [];
  try { files = walk(jsm); } catch { return 0; }
  const lines = [];
  for (const f of files.sort()) {
    const spec = 'three/addons/' + relative(jsm, f).split(/[\\/]/).join('/');
    const src = readFileSync(f, 'utf8');
    const names = new Set();
    for (const m of src.matchAll(/^export\s+(?:default\s+)?(?:async\s+)?(class|function|const|let|var)\s+([A-Za-z_$][\w$]*)/gm)) names.add(m[2]);
    for (const m of src.matchAll(/^export\s*\{([^}]*)\}/gm))
      for (const part of m[1].split(','))
        { const t = part.trim().split(/\s+as\s+/).pop().trim(); if (t && t !== 'default') names.add(t); }
    // `export default Identifier;` — common in the transpiler and loader addons
    for (const m of src.matchAll(/^export\s+default\s+([A-Z][\w$]*)\s*;/gm)) names.add(m[1] + ' (default)');
    for (const m of src.matchAll(/^export\s+default\s+(?:class|function)\s+([A-Za-z_$][\w$]*)/gm)) names.add(m[1] + ' (default)');
    if (names.size) lines.push(`${spec}\t${[...names].sort().join(' ')}`);
  }
  writeFileSync(join(outDir, 'addons.txt'),
    `# three/addons/* module paths and their exports — three@${version}\n` +
    `# ${lines.length} modules. Generated by gen-api-surface.mjs; do not edit.\n` +
    `# import-path<TAB>exported names\n` + lines.join('\n') + '\n');
  return lines.length;
}

const c = await dumpEntry('three', 'three-core.txt');
const w = await dumpEntry('three/webgpu', 'three-webgpu.txt');
const t = await dumpEntry('three/tsl', 'three-tsl.txt');
const a = threeRoot ? addonExports(threeRoot) : 0;
writeFileSync(join(outDir, 'VERSION.txt'), `three@${version}\ncore=${c} webgpu=${w} tsl=${t} addonModules=${a}\n`);
console.log(`three@${version}: core=${c} webgpu=${w} tsl=${t} addonModules=${a} → ${outDir}`);
