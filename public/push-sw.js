/* OWNER: pwa-mobile-engineer (IDEA-052b)
 *
 * The push listeners, imported INTO the generated service worker.
 *
 * WHY THIS FILE EXISTS RATHER THAN A src/sw.ts.
 *
 * Adding a `push` handler normally means switching vite-plugin-pwa from its
 * default `generateSW` strategy to `injectManifest` and owning the whole worker.
 * At the installed 0.20.5 that carries three SILENT failure modes, all measured:
 *
 *   1. The existing `workbox: { globPatterns }` is IGNORED with no warning —
 *      under injectManifest the option is `injectManifest: {...}` — quietly
 *      dropping the woff2/glb/mp3/ogg precache patterns. This is a PWA whose
 *      fonts are the visual language; losing them offline is not cosmetic.
 *   2. `registerType: "autoUpdate"` stops working after the first install.
 *      generateSW bakes in `skipWaiting()`/`clientsClaim()`; injectManifest does
 *      not, and the auto path never sends skipWaiting itself. Players would pin
 *      to an old bundle FOREVER, with no error anywhere.
 *   3. The standard dev recipe's `devOptions.type: "module"` leaks into the
 *      PRODUCTION registration, because the plugin's ternary keys off
 *      `devOptions.enabled` (true here) rather than serve-vs-build. Module
 *      service workers are unsupported in Firefox.
 *
 * `workbox.importScripts` gets the same listeners onto the same registration,
 * in the same install pass, for a three-line config change — and leaves every
 * one of those behaviours exactly as it already is. The cost is that this file
 * is plain JS with no bundler: no imports, no `import.meta.env`, and it is NOT
 * content-hashed, so the `?v=` in vite.config.ts must be bumped when it changes.
 *
 * A SECOND, SEPARATE service worker is not an option: a push subscription
 * belongs to a ServiceWorkerRegistration, and a second one would have a
 * different scope, control no clients, and have nothing to focus on a click.
 */

/* global self, clients */

self.addEventListener("push", (event) => {
  // A push with no data is legal and is used by some services as a keep-alive.
  // Showing an empty notification would be worse than showing nothing — but
  // `userVisibleOnly: true` means the platform expects SOMETHING, so fall back
  // to a generic line rather than returning silently.
  let payload = {};
  if (event.data) {
    try {
      payload = event.data.json();
    } catch {
      payload = { body: event.data.text() };
    }
  }

  const title = payload.title || "Beagle Chomp";
  const options = {
    body: payload.body || "Something happened in the garden.",
    // The big picture in the notification shade. The server sends a different
    // one per kind (a megaphone for a release note, a bell for a notice), so
    // the two are distinguishable before you read a word.
    icon: payload.icon || "icons/icon-192.png",
    // THE STATUS-BAR MARK, AND IT IS NOT A SMALL ICON. Android uses only this
    // image's ALPHA CHANNEL and paints the result white — so a normal
    // full-colour icon, opaque edge to edge, renders as a SOLID WHITE
    // RECTANGLE. That is what shipped first and what it looked like on a real
    // phone. badge-96.png is a transparent paw silhouette, generated by
    // scripts/make-badge-icon.ts and guarded by `npm run test:badge`.
    badge: "icons/badge-96.png",
    // `tag` collapses: a second notification with the same tag REPLACES the
    // first rather than stacking. The server sets one tag for announcements and
    // one per player for rank alerts, so a busy evening leaves one line.
    tag: payload.tag || "beagle-chomp",
    // Where a click should land, carried through to notificationclick below.
    data: { url: payload.url || "./" },
    // iOS supports title + body and little else — no actions, no image. Not
    // worth branching on: this is what every platform renders.
  };

  // Show the notification AND tell any open copy of the game, so the bell's
  // unread count updates without waiting for a reload. A player who is looking
  // at the menu when a note is published should see the pill appear, not
  // discover it tomorrow.
  event.waitUntil(
    Promise.all([
      self.registration.showNotification(title, options),
      (async () => {
        const windows = await clients.matchAll({ type: "window", includeUncontrolled: true });
        for (const client of windows) {
          client.postMessage({ type: "beagle-push", tag: options.tag });
        }
      })(),
    ]),
  );
});

self.addEventListener("notificationclick", (event) => {
  event.notification.close();
  const target = (event.notification.data && event.notification.data.url) || "./";

  event.waitUntil(
    (async () => {
      // FOCUS AN OPEN TAB RATHER THAN OPENING A SECOND ONE. A player who
      // already has the game open should be brought to it — opening a duplicate
      // would start a second instance of a game that holds a WebGL context and
      // an audio graph.
      const all = await clients.matchAll({ type: "window", includeUncontrolled: true });
      for (const client of all) {
        if ("focus" in client) {
          // Navigate the existing tab if the notification points somewhere
          // specific, then focus it.
          if (target !== "./" && "navigate" in client) {
            try {
              await client.navigate(target);
            } catch {
              /* cross-origin or not allowed — focusing is still the right move */
            }
          }
          return client.focus();
        }
      }
      return clients.openWindow(target);
    })(),
  );
});
